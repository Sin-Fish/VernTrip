import static org.assertj.core.api.Assertions.assertThat;

class ParseTaskSchemaCompatibilityInitializerTest {

    @Test
    void shouldPatchLegacyParseTaskTable() throws SQLException {
        DataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:parse-task-compat-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                ""
        );
        JdbcTemplate jdbcTemplate = new JdbcTemplate(dataSource);

        jdbcTemplate.execute("""
                create table parse_task (
                    id bigint generated by default as identity primary key,
                    paper_id bigint not null,
                    task_type varchar(32) not null,
                    status varchar(32) not null,
                    error_message clob,
                    created_at timestamp not null,
                    started_at timestamp,
                    finished_at timestamp,
                    constraint parse_task_status_check
                    check (status in ('FAILED', 'PENDING', 'PROCESSING', 'SUCCESS'))
                )
                """);
        jdbcTemplate.update("""
                insert into parse_task (paper_id, task_type, status, error_message, created_at, started_at, finished_at)
                values (?, ?, ?, ?, current_timestamp, null, null)
                """, 1L, "PAPER_PARSE", "PENDING", null);

        ParseTaskSchemaCompatibilityInitializer initializer = new ParseTaskSchemaCompatibilityInitializer(dataSource);
        initializer.ensureLegacyParseTaskColumns();

        Map<String, Object> taskRow = jdbcTemplate.queryForMap(
                "select queue_order, updated_at from parse_task where id = 1"
        );
        jdbcTemplate.update("insert into parse_task (paper_id, task_type, status, created_at, queue_order, updated_at) values (?, ?, ?, current_timestamp, ?, current_timestamp)",
                2L, "PAPER_PARSE", "PAUSED", 2L);
        Long maxQueueOrder = jdbcTemplate.queryForObject(
                "select coalesce(max(queue_order), 0) from parse_task where status in (?, ?)",
                Long.class,
                "PENDING",
                "PAUSED"
        );

        assertThat(((Number) taskRow.get("QUEUE_ORDER")).longValue()).isEqualTo(1L);
        assertThat(taskRow.get("UPDATED_AT")).isNotNull();
        assertThat(maxQueueOrder).isEqualTo(2L);

        try (Connection connection = dataSource.getConnection()) {
            assertThat(hasColumn(connection, "PARSE_TASK", "QUEUE_ORDER")).isTrue();
            assertThat(hasColumn(connection, "PARSE_TASK", "UPDATED_AT")).isTrue();
        }
    }

    @Test
    void shouldUpgradeLegacyStatusEnumToAllowPaused() throws SQLException {
        DataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:parse-task-enum-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                ""
        );
        JdbcTemplate jdbcTemplate = new JdbcTemplate(dataSource);

        jdbcTemplate.execute("""
                create table parse_task (
                    id bigint generated by default as identity primary key,
                    paper_id bigint not null,
                    task_type varchar(32) not null,
                    status enum('FAILED', 'PENDING', 'PROCESSING', 'SUCCESS') not null,
                    error_message clob,
                    created_at timestamp not null,
                    started_at timestamp,
                    finished_at timestamp,
                    queue_order bigint,
                    updated_at timestamp
                )
                """);
        jdbcTemplate.update("""
                insert into parse_task (paper_id, task_type, status, error_message, created_at, started_at, finished_at, queue_order, updated_at)
                values (?, ?, ?, ?, current_timestamp, null, null, ?, current_timestamp)
                """, 1L, "PAPER_PARSE", "PENDING", null, 1L);

        ParseTaskSchemaCompatibilityInitializer initializer = new ParseTaskSchemaCompatibilityInitializer(dataSource);
        initializer.ensureLegacyParseTaskColumns();

        jdbcTemplate.update("""
                insert into parse_task (paper_id, task_type, status, error_message, created_at, started_at, finished_at, queue_order, updated_at)
                values (?, ?, ?, ?, current_timestamp, null, null, ?, current_timestamp)
                """, 2L, "PAPER_PARSE", "PAUSED", null, 2L);

        Long maxQueueOrder = jdbcTemplate.queryForObject(
                "select coalesce(max(queue_order), 0) from parse_task where status in (?, ?)",
                Long.class,
                "PENDING",
                "PAUSED"
        );

        assertThat(maxQueueOrder).isEqualTo(2L);

        try (Connection connection = dataSource.getConnection()) {
            assertThat(columnTypeName(connection, "PARSE_TASK", "STATUS")).contains("PAUSED");
        }
    }

    private boolean hasColumn(Connection connection, String tableName, String columnName) throws SQLException {
        try (var resultSet = connection.getMetaData().getColumns(connection.getCatalog(), null, tableName, columnName)) {
            return resultSet.next();
        }
    }

    private String columnTypeName(Connection connection, String tableName, String columnName) throws SQLException {
        try (var resultSet = connection.getMetaData().getColumns(connection.getCatalog(), null, tableName, columnName)) {
            if (resultSet.next()) {
                return resultSet.getString("TYPE_NAME");
            }
        }
        return null;
    }
}

