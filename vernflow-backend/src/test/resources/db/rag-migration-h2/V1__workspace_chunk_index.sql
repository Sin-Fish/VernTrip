CREATE TABLE IF NOT EXISTS workspace_document_index (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source_path VARCHAR(1024) NOT NULL,
    source_label VARCHAR(1024) NOT NULL,
    section_title VARCHAR(255),
    source_signature VARCHAR(255) NOT NULL,
    chunk_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_workspace_document_index_user_path UNIQUE (user_id, source_path)
);

CREATE TABLE IF NOT EXISTS workspace_chunk_index (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    sort_index INT NOT NULL,
    chunk_text CLOB NOT NULL,
    embedding_id VARCHAR(255),
    embedding CLOB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_workspace_chunk_document
        FOREIGN KEY (document_id) REFERENCES workspace_document_index (id)
            ON DELETE CASCADE,
    CONSTRAINT uk_workspace_chunk_document_sort UNIQUE (document_id, sort_index)
);

CREATE INDEX IF NOT EXISTS idx_workspace_document_index_updated_at
    ON workspace_document_index (updated_at);

CREATE INDEX IF NOT EXISTS idx_workspace_chunk_index_document
    ON workspace_chunk_index (document_id, sort_index);
